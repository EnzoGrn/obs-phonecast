#!/usr/bin/env node
/**
 * Generates src/server/dock-html.generated.js from web/index.html.
 *
 * Why: `bun build --compile` bundles JavaScript, not arbitrary files read
 * with readFile() at runtime, so a compiled binary has no web/index.html to
 * serve and the dock would 404 on its own page. The server falls back to
 * this generated module (a plain string export, bundled like any other
 * import) when the file isn't on disk. `node src/index.js` never needs it.
 *
 * Run automatically by `npm run build*` and by the release/CI workflows.
 * The output is gitignored.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'web', 'index.html');
const TARGET = path.join(ROOT, 'src', 'server', 'dock-html.generated.js');

const html = await readFile(SOURCE, 'utf8');
const banner = '// GENERATED by scripts/embed-dock.js from web/index.html. Do not edit or commit.\n';
await writeFile(TARGET, `${banner}export default ${JSON.stringify(html)};\n`);
process.stdout.write(`embedded ${path.relative(ROOT, SOURCE)} -> ${path.relative(ROOT, TARGET)}\n`);
